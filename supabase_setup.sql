-- 7. SECURE COUNTER RPCs
CREATE OR REPLACE FUNCTION public.increment_views(target_id int8)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF target_id IS NOT NULL AND target_id > 0 THEN
    UPDATE public."Prompts"
    SET views_count = COALESCE(views_count, 0) + 1
    WHERE id = target_id AND is_published = true;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.increment_copies(target_id int8)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF target_id IS NOT NULL AND target_id > 0 THEN
    UPDATE public."Prompts"
    SET copies_count = COALESCE(copies_count, 0) + 1
    WHERE id = target_id AND is_published = true;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.increment_views(int8) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.increment_copies(int8) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.increment_views(int8) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.increment_copies(int8) TO anon, authenticated;
