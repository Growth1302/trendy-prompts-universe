ALTER TABLE public."Prompts" ALTER COLUMN description SET NOT NULL;

-- 3. BACKFILL NULL VALUES BEFORE ENFORCING CONSTRAINTS
UPDATE public."Prompts" SET views_count = 0 WHERE views_count IS NULL;
UPDATE public."Prompts" SET copies_count = 0 WHERE copies_count IS NULL;
UPDATE public."Prompts" SET likes_count = 0 WHERE likes_count IS NULL;
UPDATE public."Prompts" SET featured = false WHERE featured IS NULL;
UPDATE public."Prompts" SET trending = false WHERE trending IS NULL;
UPDATE public."Prompts" SET is_published = true WHERE is_published IS NULL;
UPDATE public."Prompts" SET status = 'published' WHERE status IS NULL;

-- 4. SCOPED PRIVILEGE MANAGEMENT
-- Revoke all table privileges on Prompts from public/anon/authenticated roles
REVOKE ALL ON TABLE public."Prompts" FROM anon, authenticated, public;

-- Grant SELECT only to public roles (Submissions/Updates/Deletes are handled by Service Role in Edge Function)
GRANT SELECT ON TABLE public."Prompts" TO anon, authenticated;

-- Dynamically revoke sequence usage from anon/authenticated
DO $$
DECLARE
    seq_name text;
BEGIN
    seq_name := pg_get_serial_sequence('public."Prompts"', 'id');
    IF seq_name IS NOT NULL THEN
        EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM anon, authenticated, public', seq_name);
    END IF;
END $$;

